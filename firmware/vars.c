/* USB_VID, USB_PID, USB_BCD: 16-bit numbers from build.env. */
#if !defined(USB_VID) || !defined(USB_PID) || !defined(USB_BCD)
#error "USB_VID, USB_PID and USB_BCD are required (build.env)"
#endif

/* Discover Identity ID header VID, then (after cert stat) product VDO. */
#define ID_VID    (USB_VID & 0xFF), (USB_VID >> 8)
#define ID_PRODUCT (USB_BCD & 0xFF), (USB_BCD >> 8), (USB_PID & 0xFF), (USB_PID >> 8)

